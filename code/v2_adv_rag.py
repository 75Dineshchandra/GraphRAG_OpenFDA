from rapidfuzz import fuzz

def parse_question(q):
    default = {"sub_queries": [q], "named": [], "scope": "specific"}
    if not FLAGS["parse"]: return default
    p = ("Return JSON for the user question.\n"
         "1. \"named\": product or drug names the user literally wrote (brand or generic names, with strengths). "
         "Do NOT include symptoms, conditions, body parts or product categories (for example 'cold', 'antacid', 'eye drops', 'soap'). Empty list if none.\n"
         "2. \"sub_queries\": split ONLY when comparing two or more named products, or when one word has two different meanings. "
         "Split by subject, never by aspect: age limits, pregnancy, dose, warnings and so on stay together in one sub-question. "
         "Each sub-question must repeat everything asked about its subject and be self-contained. Otherwise return the question unchanged. At most 3.\n"
         "3. \"scope\": \"list\" if the user wants a list of different products, else \"specific\".\n"
         "Return JSON: {\"named\": [], \"sub_queries\": [\"...\"], \"scope\": \"specific\"}\nQuestion: " + q)
    r = llm_json(p, num_predict=250)
    try:
        sq = [s.strip() for s in r["sub_queries"] if isinstance(s, str) and s.strip()][:3]
        nm_ = [n.strip() for n in r.get("named", []) if isinstance(n, str) and n.strip()]
        sc = r.get("scope") if r.get("scope") in ("specific", "list") else "specific"
        return {"sub_queries": sq or [q], "named": nm_, "scope": sc}
    except Exception: return default

def named_in(sq, named):
    # which of the named products belong to this sub-query
    t = re.sub(r"\s+", " ", sq.lower())
    return [n for n in named if re.sub(r"\s+", " ", n.lower()) in t or fuzz.partial_ratio(n.lower(), t) >= 90]

def choose_sections(sq):
    if not FLAGS["llm_sections"]: return []
    p = ("An FDA drug label has these sections: " + ", ".join(SECTION_TYPES) + ".\n"
         "Which sections are needed to answer the question below? Pick 1 to 5 section names from that list only.\n"
         "Return JSON: {\"sections\": [\"...\"]}\nQuestion: " + sq)
    r = llm_json(p, num_predict=100)
    try: return [s for s in r["sections"] if s in SECTION_TYPES]
    except Exception: return []

# ===== 8. find drugs: drug mode (named products) or symptom mode (search -> rerank -> judge) =====
def norm_txt(s): return re.sub(r"\s+", " ", s.lower()).strip()
def contains(hay, needle):
    n = norm_txt(needle).strip(" .;:-•*\"'")
    return len(n) >= 8 and n in norm_txt(hay)

_LH = {}
def label_hash(d):
    if d not in _LH:
        txt = "||".join(sorted(norm_txt(section_text(sid)) for sid, t in DRUG_SECTIONS[d] if t not in EXCLUDE_SECTIONS))
        _LH[d] = hashlib.md5(txt.encode()).hexdigest()
    return _LH[d]

def dedupe_cap(drug_ids, cap):
    out, seen = [], set()
    for d in drug_ids:
        h = label_hash(d)
        if h in seen: continue
        seen.add(h); out.append(d)
        if len(out) >= cap: break
    return out

JUDGE_PROMPT = ("You judge text from an FDA drug label.\nQuestion: <<Q>>\nExcerpt (drug: <<D>>, section: <<S>>):\n<<T>>\n\n"
                "Answer relevant=true ONLY if the excerpt itself states the use or fact the question asks for. "
                "Related, similar or general text is relevant=false. If true, copy the single most useful sentence from the excerpt EXACTLY as written.\n"
                "Return JSON: {\"relevant\": true, \"sentence\": \"...\"} or {\"relevant\": false, \"sentence\": \"\"}")

def symptom_candidates(sq):
    idxA = np.concatenate([IDX_BY_SECTION[s] for s in ("indications_and_usage", "purpose") if s in IDX_BY_SECTION])
    fused = defaultdict(float)
    for i, s, c in hybrid_rank([sq], idxA, k=SEARCH_K): fused[i] += s            # indications + purpose
    for i, s, c in hybrid_rank([sq], None, k=15): fused[i] += 0.5 * s             # safety net: all sections
    cand = sorted(fused, key=lambda i: -fused[i])[:SEARCH_K]
    scores = {i: 0.0 for i in cand}
    if FLAGS["rerank"] and cand:
        sc = get_reranker().predict([(sq, CHUNKS[i]["stamped"]) for i in cand], show_progress_bar=False)
        scores = {i: float(s) for i, s in zip(cand, sc)}
        cand = sorted(cand, key=lambda i: -scores[i])[:RERANK_KEEP]
    else: cand = cand[:RERANK_KEEP]
    return cand, scores

def find_drugs(sq, scope, named, verbose=True):
    cap = LIST_CAP if scope == "list" else SPECIFIC_CAP
    hits = alias_hits(sq) if FLAGS["alias"] else []                  # alias words are rare, so safe on the whole sentence
    for n in named_in(sq, named): hits += detect_entities(n)          # drug names only from products the user named
    log = {"cands": 0, "judged_yes": 0, "judged_verified": 0}
    if hits:                                                          # DRUG MODE
        order = []
        for h in sorted(hits, key=lambda h: (-h["n"], len(h["matched"]))):
            if h["drug_id"] not in order: order.append(h["drug_id"])
        return dedupe_cap(order, cap), "drug", [h["matched"] for h in hits[:5]], log, 0.0
    cand, scores = symptom_candidates(sq)                             # SYMPTOM MODE
    log["cands"] = len(cand); kept = []
    for i in cand:
        c = CHUNKS[i]
        if not FLAGS["judge"]: kept.append(i); continue
        r = llm_json(JUDGE_PROMPT.replace("<<Q>>", sq).replace("<<D>>", c["drug"]).replace("<<S>>", c["section"]).replace("<<T>>", c["text"]), num_predict=200)
        try: rel, sent = bool(r.get("relevant")), str(r.get("sentence", ""))
        except Exception: rel, sent = False, ""
        if rel:
            log["judged_yes"] += 1
            if contains(c["text"], sent): log["judged_verified"] += 1; kept.append(i)   # code verifies the copied sentence
    if not kept and JUDGE_FALLBACK: kept = cand[:JUDGE_FALLBACK]; log["fallback"] = True
    by = defaultdict(list)
    for i in kept: by[CHUNKS[i]["drug_id"]].append(scores.get(i, 0.0))
    order = [d for d, v in sorted(by.items(), key=lambda x: -sum(sorted(x[1], reverse=True)[:2]))]   # top-2 chunk scores, not chunk count
    top = max([float(EMB[i] @ qvec(sq)) for i in kept], default=0.0)
    return dedupe_cap(order, cap), "symptom", [], log, top

