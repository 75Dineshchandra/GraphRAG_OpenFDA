# ===== 6. entity + alias detection (data-driven, no hand-written word lists) =====
def norm_tokens(s):
    s = re.sub(r"(\d)([a-z])", r"\1 \2", s.lower())
    return [t for t in re.findall(r"[a-z0-9]+", s) if t not in {"and", "the", "of", "with"}]

name_vocab = defaultdict(set)                                   # word -> drugs having it in their NAME
for g, nm in GENERIC_NAME.items():
    for t in set(norm_tokens(nm)): name_vocab[t].add(g)
for b, nm in BRAND_NAME.items():
    gens = BRAND_TO_GENERIC.get(b, [])
    for t in set(norm_tokens(nm)): name_vocab[t].update(gens)

dom_re = re.compile(r"\b([A-Za-z0-9][A-Za-z0-9\-]{2,})\.(?:com|net|org|co)\b")
tm_re  = re.compile(r"\b([A-Z][A-Za-z0-9\-]{3,})\s?(?:™|®|\(TM\)|TM\b)")
cap_re = re.compile(r"\b[A-Z][a-z]{4,}[A-Za-z\-]*\b")
text_vocab, low_df = defaultdict(set), Counter()
alias_dom, cap_hits = defaultdict(set), defaultdict(set)
squash = lambda s: re.sub(r"[^a-z0-9]", "", s.lower())
for c in tqdm(CHUNKS, desc="scanning label text"):
    d, t = c["drug_id"], c["text"]
    toks = set(norm_tokens(t))
    for w in toks:
        low_df[w] += 1
        if w in name_vocab: text_vocab[w].add(d)
    for m in dom_re.findall(t) + tm_re.findall(t): alias_dom[squash(m)].add(d)
    for m in set(cap_re.findall(t)): cap_hits[squash(m)].add(d)

# category-word filter: a name word is "specific" only if drugs that have it in the NAME also mention it in their TEXT
TOK_PREC = {}
for t, nd in name_vocab.items():
    td = text_vocab.get(t, set()); TOK_PREC[t] = (len(nd & td) / len(td)) if td else 1.0
ENT, dropped = [], []
for kind, table in (("generic", GENERIC_NAME), ("brand", BRAND_NAME)):
    for eid, nm in table.items():
        if kind == "brand" and not BRAND_TO_GENERIC.get(eid): continue
        ts = frozenset(norm_tokens(nm))
        if not ts: continue
        (ENT if max(TOK_PREC[t] for t in ts) >= PRECISION_MIN else dropped).append((ts, nm, kind, eid))
print(f"entity table kept={len(ENT):,} | dropped as category words={len(dropped):,}")

# alias table: rare product-like words found only inside label text (domains, TM marks, rare capitalised words)
ALIAS = defaultdict(set)
for a, ds in alias_dom.items():
    if len(ds) <= 5 and len(a) >= 4: ALIAS[a] |= ds
for a, ds in cap_hits.items():
    if len(ds) <= 3 and len(a) >= 5 and a not in name_vocab and low_df.get(a, 0) <= 6: ALIAS[a] |= ds
print("alias entries:", len(ALIAS))

def detect_entities(query):
    qt = set(norm_tokens(query)); hits = []
    for ts, nm, kind, eid in ENT:
        if ts <= qt or (len(ts) >= 4 and len(ts & qt) / len(ts) >= 0.8): hits.append((ts, nm, kind, eid))
    keep = [h for h in hits if not any(h[0] < o[0] for o in hits)]
    out, seen = [], set()
    for ts, nm, kind, eid in sorted(keep, key=lambda h: (-len(h[0]), len(h[1]))):
        for g in ([eid] if kind == "generic" else BRAND_TO_GENERIC.get(eid, [])):
            if g not in seen: seen.add(g); out.append({"drug_id": g, "matched": nm, "n": len(ts)})
    return out

def alias_hits(query):
    toks = [squash(t) for t in re.split(r"\s+", query)]
    cand = {t for t in toks if len(t) >= 4} | {a + b for a, b in zip(toks, toks[1:]) if a and b}
    out = []
    for a in cand:
        for g in ALIAS.get(a, ()): out.append({"drug_id": g, "matched": f"alias:{a}", "n": 99})
    return out

