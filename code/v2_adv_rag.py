def _embed_call(texts):
    r = requests.post(EMBED_URL, json={"model": EMBED_MODEL, "input": texts, "truncate": True}, timeout=300)
    r.raise_for_status(); return r.json()["embeddings"]
def embed_query(q):
    return np.array(_embed_call(["search_query: " + q])[0], dtype="float32")

def llm(prompt, temperature=0.1, num_predict=500, json_mode=False, sleep=True, tries=4):
    p = {"model": LLM_MODEL, "prompt": prompt, "stream": False, "keep_alive": "30m",
         "options": {"temperature": temperature, "num_ctx": 8192, "num_predict": num_predict}}
    if json_mode: p["format"] = "json"
    out = ""
    for k in range(tries):
        try:
            r = requests.post(GEN_URL, json=p, timeout=900); r.raise_for_status()
            out = r.json()["response"].strip(); break
        except Exception as e:                                   # HTTP 500 etc: wait, retry, never kill the question
            print(f"  llm retry {k+1}/{tries}: {repr(e)[:80]}"); time.sleep(10 * (k + 1))
    if sleep and SLEEP_CALL: time.sleep(SLEEP_CALL)
    return out
def llm_json(prompt, **kw):
    raw = llm(prompt, json_mode=True, **kw)
    try: return json.loads(raw)
    except Exception:
        m = re.search(r"\{.*\}", raw, re.S)
        try: return json.loads(m.group(0)) if m else None
        except Exception: return None

_QCACHE = {}
def qvec(q):
    if q not in _QCACHE:
        v = embed_query(q); _QCACHE[q] = v / (np.linalg.norm(v) + 1e-9)
    return _QCACHE[q]
def dense_topk(qv, allowed, k):
    if allowed is None:
        _, I = INDEX.search(qv.reshape(1, -1).astype("float32"), k); return [int(i) for i in I[0] if i >= 0]
    sims = EMB[allowed] @ qv
    return [int(allowed[o]) for o in np.argsort(-sims)[:k]]
def bm25_topk(q, allowed, k):
    toks = tokenize(q)
    if not toks: return []
    scores = BM25.get_scores(toks)
    if allowed is None:
        cand = np.argpartition(-scores, min(k, len(scores) - 1))[:k]; cand = cand[np.argsort(-scores[cand])]
    else:
        cand = allowed[np.argsort(-scores[allowed])[:k]]
    return [int(c) for c in cand if scores[c] > 0]
def rrf(lists):
    out = defaultdict(float)
    for lst in lists:
        for rank, idx in enumerate(lst, start=1): out[idx] += 1.0 / (RRF_K + rank)
    return out
def hybrid_rank(queries, allowed=None, k=50):
    lists, qvs = [], []
    for q in queries:
        qv = qvec(q); qvs.append(qv)
        lists.append(dense_topk(qv, allowed, k)); lists.append(bm25_topk(q, allowed, k))
    fused = sorted(rrf(lists).items(), key=lambda x: -x[1])[:k]
    return [(i, s, max(float(EMB[i] @ qv) for qv in qvs)) for i, s in fused]

