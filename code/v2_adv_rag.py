EXTRACT_PROMPT = ("Question: <<Q>>\nLabel section (<<S>>) of <<D>>:\n<<T>>\n\n"
                  "Copy, word for word, every sentence or phrase from this section that helps answer the question. One per line. "
                  "If nothing helps, reply exactly NONE. Add nothing else.")

def get_sections(d):
    out = []
    for sid, t in DRUG_SECTIONS[d]:
        if t in EXCLUDE_SECTIONS: continue
        tx = section_text(sid)
        if tx: out.append((sid, t, tx))
    return out

def pick_sections(d, sq, chosen):
    secs = get_sections(d)
    first = [s for s in secs if s[1] in chosen]; rest = [s for s in secs if s[1] not in chosen]
    if FLAGS["rerank"] and rest:
        sc = get_reranker().predict([(sq, s[2][:1500]) for s in rest], show_progress_bar=False)
        rest = [s for _, s in sorted(zip(sc, rest), key=lambda x: -x[0])]
    return first + rest[:max(0, EXTRACT_SECTIONS - len(first))]

def extract_for_drug(d, sq, chosen, sources):
    snips = []
    for sid, stype, tx in pick_sections(d, sq, chosen):
        tx = tx[:SECTION_CHARS]
        if not FLAGS["extract"]: lines = [tx[:700]]
        else:
            raw = llm(EXTRACT_PROMPT.replace("<<Q>>", sq).replace("<<S>>", stype).replace("<<D>>", GENERIC_NAME[d]).replace("<<T>>", tx), num_predict=300)
            lines = [] if raw.strip().upper().startswith("NONE") else [re.sub(r"^[\-\*•\d\.\)\s]+", "", l).strip() for l in raw.splitlines()]
        seen = set()
        for l in lines:
            if len(l) < 8 or l in seen or not (contains(tx, l) or not FLAGS["extract"]): continue   # keep only verified copies
            seen.add(l)
            s = {"tag": f"S{len(sources)+1}", "drug_id": d, "drug": GENERIC_NAME[d], "section": stype, "node": sid, "text": l, "sq": sq}
            sources.append(s); snips.append(s)
    return snips

# ===== 10. per-drug answer, quote + support check, merge, code-based abstain =====
GEN_PROMPT = ("Answer the question using ONLY the numbered label snippets below. Rules: each claim is one full sentence that states a fact and names the drug; "
              "a drug name alone is not a claim. For each claim give at most 3 source tags and copy the exact words from the snippet that support it. "
              "If the snippets do not answer the question, return an empty claims list.\n"
              "Return JSON: {\"claims\": [{\"claim\": \"...\", \"sources\": [\"S1\"], \"quote\": \"...\"}]}\n"
              "Question: <<Q>>\nSnippets:\n<<SN>>")

def generate_claims(question, snips):
    if not snips: return []
    sn = "\n".join(f"[{s['tag']}] ({s['drug']} | {s['section']}) {s['text']}" for s in snips[:15])   # cap prompt size
    r = llm_json(GEN_PROMPT.replace("<<Q>>", question).replace("<<SN>>", sn), num_predict=600)
    try: cl = [c for c in r["claims"] if isinstance(c, dict) and isinstance(c.get("claim"), str)]
    except Exception: return []
    return [c for c in cl if len(c["claim"].split()) >= 5 and len(c.get("sources") or []) <= 4]   # drop name-only / over-cited claims

def check_claims(claims, sources):
    by = {s["tag"]: s for s in sources}
    for c in claims:
        tags = [t for t in (c.get("sources") or []) if isinstance(t, str)]
        c["tags"] = tags
        if not tags: c["status"] = "no_citation"; continue
        if any(t not in by for t in tags): c["status"] = "invalid_citation"; continue
        ev = "\n".join(by[t]["text"] for t in tags)
        if FLAGS["quote_check"] and not contains(ev, str(c.get("quote", ""))): c["status"] = "quote_not_in_source"; continue
        v = llm(f"Label text:\n{ev}\n\nClaim: {c['claim']}\n\nDoes the label text directly support the claim? Answer with one word: YES or NO.",
                temperature=0.0, num_predict=3)
        c["status"] = "supported" if v.upper().startswith("YES") else "unsupported"
    return claims

def answer_question(question, verbose=True):
    t0 = time.time()
    if verbose: print("\nQUESTION:", question)
    parsed = parse_question(question)
    sources, rows, modes, ents, logs, tops, extracted = [], [], [], [], [], [], {}
    for sq in parsed["sub_queries"]:
        chosen = choose_sections(sq)
        drugs, mode, e, log, top = find_drugs(sq, parsed["scope"], parsed["named"], verbose)
        modes.append(mode); ents += e; logs.append(log); tops.append(top)
        if verbose: print(f"  sub-query: {sq!r} | mode={mode} | scope={parsed['scope']} | named={parsed['named']} | sections={chosen} | drugs={[GENERIC_NAME[d] for d in drugs]} | judge={log}")
        for d in drugs:
            if d not in extracted: extracted[d] = extract_for_drug(d, sq, chosen, sources)   # each drug is extracted once
            rows.append({"drug_id": d, "drug": GENERIC_NAME[d], "sq": sq, "snips": extracted[d]})
    claims, reason = [], None
    if not rows: reason = "no drugs found"
    elif not sources: reason = "no verified evidence"
    else:
        by_drug = {}
        for r in rows: by_drug.setdefault(r["drug_id"], r)
        groups = [(r["snips"], r["sq"]) for r in by_drug.values()] if FLAGS["per_drug"] else [(sources, question)]
        for snips, sq in groups: claims += generate_claims(sq, snips)
        claims = check_claims(claims, sources)
        if not any(c["status"] == "supported" for c in claims): reason = "no supported claims"
    final = ABSTAIN_TEXT if reason else "\n".join(("- " if c["status"] == "supported" else f"- [FLAGGED: {c['status']}] ") + c["claim"] + " " + "".join(f"[{t}]" for t in c["tags"]) for c in claims)
    rec = {"question": question, "sub_queries": parsed["sub_queries"], "named": parsed["named"], "scope": parsed["scope"], "mode": "+".join(sorted(set(modes))),
           "entities": ents, "intent": [], "drugs": [r["drug"] for r in rows], "sections_in_context": sorted({s["section"] for s in sources}),
           "sources": [{k: v for k, v in s.items() if k not in ("drug_id", "sq")} | {"cos": None} for s in sources], "top_cos": round(max(tops, default=0.0), 3),
           "context_chars": sum(len(s["text"]) for s in sources), "judge": logs, "claims": claims,
           "unsupported_rate": round(sum(c["status"] != "supported" for c in claims) / len(claims), 3) if claims else None,
           "raw_answer": final, "abstained": bool(reason), "abstain_reason": reason, "final_answer": final, "seconds": round(time.time() - t0, 1)}
    if verbose: print("  ANSWER:\n", final, f"\n  done in {rec['seconds']}s | abstain={rec['abstain_reason']}")
    return rec

