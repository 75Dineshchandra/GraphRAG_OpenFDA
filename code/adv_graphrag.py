def section_text(sid):
    txt = G.nodes[sid].get("description") or ""
    txt = html.unescape(re.sub(r"<[^>]+>", " ", txt))
    return re.sub(r"\s+", " ", txt).strip()

def split_units(text):
    # split on ' ; ', bullets and sentence ends (the text is joined with ' ; ', so NLTK would fail)
    parts = re.split(r"\s;\s|\s•\s|(?<=[.!?])\s+(?=[A-Z])", text)
    units = []
    for p in parts:
        p = p.strip()
        while len(p) > MAX_CHARS:                       # hard-split very long units on a word boundary
            cut = p.rfind(" ", 0, MAX_CHARS); cut = cut if cut > 100 else MAX_CHARS
            units.append(p[:cut].strip()); p = p[cut:].strip()
        if p: units.append(p)
    return units

def window_units(units):
    chunks, cur, cur_len = [], [], 0
    for u in units:
        if cur and cur_len + len(u) + 3 > MAX_CHARS:
            chunks.append(" ; ".join(cur))
            keep = cur[-OVERLAP_UNITS:] if (OVERLAP_UNITS > 0 and len(cur) >= 3) else []
            if keep and sum(len(x) for x in keep) + len(u) + 3 > MAX_CHARS: keep = []
            cur, cur_len = list(keep), sum(len(x) + 3 for x in keep)
        cur.append(u); cur_len += len(u) + 3
    if cur: chunks.append(" ; ".join(cur))
    return chunks

