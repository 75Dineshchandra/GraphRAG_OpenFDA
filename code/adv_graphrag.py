# ===== STEP 9: hybrid retrieval (dense + BM25 + RRF) =====
_QCACHE = {}
def qvec(q):
    if q not in _QCACHE:
        v = embed_texts([q], "search_query: ")[0]; _QCACHE[q] = v / (np.linalg.norm(v) + 1e-9)
    return _QCACHE[q]

def dense_topk(qv, allowed, k):
    if allowed is None:                                   # unfiltered: FAISS
        _, I = INDEX.search(qv.reshape(1, -1).astype("float32"), k)
        return [int(i) for i in I[0] if i >= 0]
    sims = EMB[allowed] @ qv                              # filtered: exact scoring on the subset
    return [int(allowed[o]) for o in np.argsort(-sims)[:k]]

def bm25_topk(q, allowed, k):
    toks = tokenize(q)
    if not toks: return []
    scores = BM25.get_scores(toks)
    if allowed is None:
        cand = np.argpartition(-scores, min(k, len(scores) - 1))[:k]; cand = cand[np.argsort(-scores[cand])]
    else:
        cand = allowed[np.argsort(-scores[allowed])[:k]]
    return [int(c) for c in cand if scores[c] > 0]

def rrf(lists, weights=None):
    out = defaultdict(float)
    for li, lst in enumerate(lists):
        w = 1.0 if weights is None else weights[li]
        for rank, idx in enumerate(lst, start=1): out[idx] += w / (RRF_K + rank)
    return out

def hybrid_rank(queries, allowed=None, k=50):
    # returns [(chunk_idx, rrf_score, best_cosine)] sorted by rrf
    lists, qvs = [], []
    for q in queries:
        qv = qvec(q); qvs.append(qv)
        lists.append(dense_topk(qv, allowed, k)); lists.append(bm25_topk(q, allowed, k))
    fused = sorted(rrf(lists).items(), key=lambda x: -x[1])[:k]
    return [(i, s, max(float(EMB[i] @ qv) for qv in qvs)) for i, s in fused]

