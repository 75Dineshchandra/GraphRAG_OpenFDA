# ===== STEP 11: retrieve = route -> rank drugs -> select chunks within token budget =====
def select_chunks(drug_id, wanted, variants, budget_chars):
    allowed = np.array([i for i in IDX_BY_DRUG.get(drug_id, []) if CHUNKS[i]["section"] in wanted])
    if len(allowed) == 0: return []
    ranked = hybrid_rank(variants, allowed, k=len(allowed))
    chosen, used, seen_sec = [], 0, set()
    for i, s, c in ranked:                                # pass 1: best chunk of every wanted section
        sec = CHUNKS[i]["section"]
        if sec not in seen_sec and used + len(CHUNKS[i]["text"]) <= budget_chars:
            chosen.append((i, c)); seen_sec.add(sec); used += len(CHUNKS[i]["text"])
    done = {i for i, _ in chosen}
    for i, s, c in ranked:                                # pass 2: fill remaining budget by relevance
        if i not in done and used + len(CHUNKS[i]["text"]) <= budget_chars:
            chosen.append((i, c)); used += len(CHUNKS[i]["text"])
    chosen.sort(key=lambda x: (SECTION_ORDER.index(CHUNKS[x[0]]["section"]) if CHUNKS[x[0]]["section"] in SECTION_ORDER else 99, x[0]))
    return chosen

def retrieve(query, verbose=True):
    variants = expand_queries(query)
    ents, intent = detect_entities(query), detect_intent(query)
    if ents:
        mode = "drug"; drug_order = [e["drug_id"] for e in ents]
        wanted = set(intent) if intent else set(DEFAULT_SECTIONS_DRUG)
    else:
        mode = "symptom"
        idxA = np.concatenate([IDX_BY_SECTION[s] for s in ("indications_and_usage", "purpose") if s in IDX_BY_SECTION])
        resA = hybrid_rank(variants, idxA, k=SYMPTOM_FETCH)      # symptom route: indications + purpose only
        resB = hybrid_rank(variants, None, k=SYMPTOM_FETCH)      # safety net: all sections (catches unknown brand names)
        ds = defaultdict(list)
        for i, s, c in resA: ds[CHUNKS[i]["drug_id"]].append(s)
        for i, s, c in resB: ds[CHUNKS[i]["drug_id"]].append(0.5 * s)
        agg = {d: sum(sorted(v, reverse=True)[:3]) for d, v in ds.items()}
        drug_order = [d for d, _ in sorted(agg.items(), key=lambda x: -x[1])][:MAX_DRUGS]
        wanted = set(intent) | {"indications_and_usage", "purpose"}
        if not intent: wanted |= {"warnings", "do_not_use"}
    if verbose:
        print(f"  mode={mode} | entities={[e['matched'] for e in ents]} | intent={intent} | wanted={sorted(wanted)}")
    per_drug = (TOTAL_CONTEXT_TOKENS * CHARS_PER_TOKEN) // max(1, len(drug_order))
    drugs, sources, top_cos = [], [], 0.0
    for d in drug_order:
        sel = select_chunks(d, wanted, variants, per_drug)
        have = {CHUNKS[i]["section"] for i in IDX_BY_DRUG.get(d, [])}
        missing = [s for s in intent if s not in have]
        drugs.append({"drug_id": d, "drug": GENERIC_NAME[d], "missing_sections": missing, "n_chunks": len(sel)})
        for i, c in sel:
            sources.append({"tag": f"S{len(sources)+1}", "idx": i, "drug": CHUNKS[i]["drug"], "section": CHUNKS[i]["section"],
                            "node": CHUNKS[i]["cid"], "cos": round(c, 3), "text": CHUNKS[i]["text"]})
            top_cos = max(top_cos, c)
        if verbose: print(f"  drug: {GENERIC_NAME[d]} | chunks={len(sel)} | missing={missing}")
    return {"mode": mode, "entities": [e["matched"] for e in ents], "intent": intent, "drugs": drugs,
            "sources": sources, "top_cos": round(top_cos, 3)}

# ===== STEP 12: prompt, generation, abstention, support check =====
ABSTAIN_TEXT = "INSUFFICIENT FDA DATA: The retrieved label text does not contain this information."

def build_prompt(question, ret):
    parts = []
    for d in ret["drugs"]:
        parts.append(f"=== DRUG: {d['drug']} ===")
        if d["missing_sections"]:
            parts.append(f"NOTE: this label has NO text for: {', '.join(d['missing_sections'])}.")
        for s in [x for x in ret["sources"] if x["drug"] == d["drug"]]:
            parts.append(f"[{s['tag']}] ({s['section']}) {s['text']}")
    return ("You answer ONLY from the FDA drug label excerpts below.\nRULES:\n"
            "1. Use only the excerpts. Never use outside knowledge.\n"
            "2. Write short bullet points. Every bullet ends with its source tag(s), e.g. [S2] or [S1][S3].\n"
            "3. Keep drugs separate: start each bullet with the drug name.\n"
            f"4. If the excerpts do not answer the question, reply exactly: {ABSTAIN_TEXT}\n"
            "5. Give no medical advice beyond what the label says.\n\n"
            "EXCERPTS:\n" + "\n".join(parts) + f"\n\nQUESTION: {question}\n\nANSWER:\n")

def parse_claims(answer):
    claims = []
    for line in answer.splitlines():
        line = line.strip()
        if not line or ABSTAIN_TEXT[:20] in line: continue
        tags = re.findall(r"\[S(\d+)\]", line)
        text = re.sub(r"\[S\d+\]", "", line).lstrip("-*• ").strip()
        if tags or (re.match(r"^[-*•\d]", line) and len(text) > 25) or len(text) > 60:
            claims.append({"claim": text, "tags": [f"S{t}" for t in tags]})
    return claims

def support_check(claims, sources):
    by_tag = {s["tag"]: s for s in sources}
    for c in claims:
        if not c["tags"]: c["status"] = "no_citation"; continue
        bad = [t for t in c["tags"] if t not in by_tag]
        if bad: c["status"] = "invalid_citation"; continue
        evidence = "\n".join(by_tag[t]["text"] for t in c["tags"])
        v = llm(f"Label text:\n{evidence}\n\nClaim: {c['claim']}\n\nDoes the label text directly support the claim? "
                "Answer with one word: YES or NO.", temperature=0.0, num_predict=3)
        c["status"] = "supported" if v.upper().startswith("YES") else "unsupported"
    return claims

def answer_question(question, verbose=True):
    t0 = time.time()
    if verbose: print("\nQUESTION:", question)
    ret = retrieve(question, verbose)
    rec = {"question": question, "mode": ret["mode"], "entities": ret["entities"], "intent": ret["intent"],
           "drugs": [d["drug"] for d in ret["drugs"]], "sections_in_context": sorted({s["section"] for s in ret["sources"]}),
           "sources": [{k: v for k, v in s.items() if k != "text"} for s in ret["sources"]], "top_cos": ret["top_cos"],
           "context_chars": sum(len(s["text"]) for s in ret["sources"]), "claims": [], "unsupported_rate": None}
    reason = None
    if not ret["sources"]: reason = "no chunks retrieved"
    elif ret["mode"] == "symptom" and ret["top_cos"] < ABSTAIN_COS: reason = f"top cosine {ret['top_cos']} < {ABSTAIN_COS}"
    if reason:
        if verbose: print("  ABSTAIN before LLM:", reason)
        rec.update(raw_answer=ABSTAIN_TEXT, final_answer=ABSTAIN_TEXT, abstained=True, abstain_reason=reason)
    else:
        if verbose: print(f"  context={rec['context_chars']} chars, {len(ret['sources'])} chunks | generating ...")
        raw = llm(build_prompt(question, ret))
        rec["raw_answer"], rec["abstained"], rec["abstain_reason"] = raw, ABSTAIN_TEXT[:20] in raw, "llm" if ABSTAIN_TEXT[:20] in raw else None
        claims = support_check(parse_claims(raw), ret["sources"])
        rec["claims"] = claims
        if claims: rec["unsupported_rate"] = round(sum(c["status"] != "supported" for c in claims) / len(claims), 3)
        rec["final_answer"] = "\n".join(("- " if c["status"] == "supported" else f"- [FLAGGED: {c['status']}] ") + c["claim"] + " " + "".join(f"[{t}]" for t in c["tags"]) for c in claims) or raw
        if verbose:
            print("  RAW ANSWER:\n", raw)
            print("  SUPPORT CHECK:", Counter(c["status"] for c in claims), "| unsupported rate:", rec["unsupported_rate"])
    rec["seconds"] = round(time.time() - t0, 1)
    if verbose: print(f"  done in {rec['seconds']}s")
    return rec, ret

