def detect_entities(query):
    qt = set(norm_tokens(query)); hits = []
    for ts, nm, kind, eid in ENT:
        if ts <= qt or (len(ts) >= 4 and len(ts & qt) / len(ts) >= 0.8): hits.append((ts, nm, kind, eid))
    keep = [h for h in hits if not any(h[0] < o[0] for o in hits)]       # drop names contained in a longer matched name
    keep.sort(key=lambda h: -len(h[0]))
    out, seen = [], set()
    for ts, nm, kind, eid in keep:
        gens = [eid] if kind == "generic" else BRAND_TO_GENERIC.get(eid, [])
        for g in gens:
            if g not in seen: seen.add(g); out.append({"drug_id": g, "matched": nm, "kind": kind})
    return out[:MAX_DRUGS]

