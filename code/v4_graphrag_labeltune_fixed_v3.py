_QCACHE = {}
def qvec(q):                                    # CHANGED: always a flat 768-vector (fixes the (1,768) crash)
    if q not in _QCACHE:
        v = np.asarray(_embed_call(["search_query: " + q])[0], dtype="float32").reshape(-1)
        _QCACHE[q] = v / (np.linalg.norm(v) + 1e-9)
