# ===== 8. parse the tuned model's output, answer, verify =====
TAG_RE = r"\[S(\d+)(?:\s*[-\u2013]\s*S?(\d+))?\]"
def get_tags(text):
    tags = []
    for a, b in re.findall(TAG_RE, text): tags += [f"S{n}" for n in range(int(a), int(b) + 1)] if b else [f"S{a}"]
    return list(dict.fromkeys(tags))

def split_reasoning(raw):
    """Model writes 'Reasoning: <thinking>' + blank line + '- bullet [S1]'. Return (reasoning, answer_text)."""
    raw = raw.strip()
    m = re.match(r"(?is)^\s*Reasoning:\s*(.*)$", raw)
    if not m: return "", raw
    rest = m.group(1)
    b = re.search(r"\n\s*\n(?=\s*[-*\u2022]\s)", rest) or re.search(r"\n\s*\n(?=\s*INSUFFICIENT FDA DATA)", rest)
    if b: return rest[:b.start()].strip(), rest[b.end():].strip()
    b = re.search(r"(?m)^\s*[-*\u2022]\s", rest)
    if b: return rest[:b.start()].strip(), rest[b.start():].strip()
    i = rest.find(ABSTAIN_TEXT[:20])
    if i >= 0: return rest[:i].strip(), rest[i:].strip()
    return rest.strip(), ""                      # no answer written (cut off or off-format)

def parse_answer(raw):
    reasoning, ans = split_reasoning(raw)
    claims = []
    for line in ans.splitlines():
        line = line.strip()
        if not line: continue
        if ABSTAIN_TEXT[:20] in line:
            claims.append({"claim": ABSTAIN_TEXT, "tags": [], "gap": True}); continue
        tags = get_tags(line)
        if not (line[0] in "-*\u2022" or tags): continue         # reasoning text is never a claim
        text = line.lstrip("-*\u2022 ").strip()
        claims.append({"claim": re.sub(r"\[S[\d\s\-\u2013S]*\]", "", text).strip(), "tags": tags, "gap": text.lower().startswith("gap:")})
    return reasoning, claims

CSTOP = STOP | {"this","that","from","have","with","text","label","retrieved","product","use","used"}
def overlap(claim, ev):
    cw = {w for w in re.findall(r"[a-z0-9]+", claim.lower()) if len(w) >= 4 and w not in CSTOP}
    ew = set(re.findall(r"[a-z0-9]+", ev.lower()))
    return (len(cw & ew) / len(cw)) if cw else 1.0

def verify(claims, sources):
    by = {s["tag"]: s for s in sources}
    for c in claims:
        if c["gap"]: c["status"] = "gap"; continue
        if not c["tags"]: c["status"] = "no_citation"; continue
        if any(t not in by for t in c["tags"]): c["status"] = "invalid_citation"; continue
        ev = "\n".join(by[t]["text"] for t in c["tags"])
        if overlap(c["claim"], ev) >= 0.8: c["status"] = "supported"; continue
        v = llm(f"Label text:\n{ev}\n\nClaim: {c['claim']}\n\nDoes the label text directly support the claim? Answer with one word: YES or NO.",
                model=AUX_MODEL, temperature=0.0, num_predict=3)
        c["status"] = "supported" if v.upper().startswith("YES") else "unsupported"
    return claims

def generate(user):
    raw = llm(user, model=ANSWER_MODEL, system=SYSTEM_PROMPT, num_predict=ANSWER_TOKENS, stop=STOPS)
    ptoks, retried = META["prompt_tokens"], False
    if META["done_reason"] == "length" and not split_reasoning(raw)[1]:      # reasoning ate the budget: retry once with more room
        room = NUM_CTX - ptoks - 50
        if room > ANSWER_TOKENS:
            raw = llm(user, model=ANSWER_MODEL, system=SYSTEM_PROMPT, num_predict=min(ANSWER_TOKENS * 2, room), stop=STOPS); retried = True
    return raw, ptoks, retried, META["done_reason"] == "length"

def answer_question(q, verbose=True):
    t0 = time.time(); named = named_drugs(q); hits = list(LAST_HITS)
    if named: mode, groups, how = "drug", [{"label": "named", "drugs": named}], "named"
    else: groups, how = symptom_groups(q); mode = "symptom"
    k = max(1, TOP_PASS // len(groups)); groups_drugs = [g["drugs"][:k] for g in groups] if not named else [named]
    if not any(groups_drugs):
        return {"question": q, "mode": mode, "drugs": [], "sources": [], "claims": [], "abstained": True, "abstain_reason": "no chunks retrieved",
                "final_answer": ABSTAIN_TEXT, "raw_answer": ABSTAIN_TEXT, "seconds": round(time.time() - t0, 1), "sections_in_context": []}
    shrink = 1.0
    while True:
        context, sources = build_context(q, groups_drugs, shrink, [g["label"] if how == "llm-split" else None for g in groups])
        user = build_prompt(q, context)
        if (len(user) + len(SYSTEM_PROMPT)) / 3.5 + ANSWER_TOKENS <= NUM_CTX or shrink < 0.3: break
        shrink *= 0.8
    raw, ptoks, retried, truncated = generate(user)
    reasoning, claims = parse_answer(raw)
    if FLAGS["verify"]: claims = verify(claims, sources)
    real = [c for c in claims if not c["gap"]]
    rate = round(sum(c.get("status") != "supported" for c in real) / len(real), 3) if real else None
    if claims:
        final = "\n".join(("- " if c.get("status") in ("supported", "gap", None) else f"- [FLAGGED: {c['status']}] ") + c["claim"] + " " + "".join(f"[{t}]" for t in c["tags"]) for c in claims)
    else: final = "(no bullet answer produced, see raw_answer)"
    reason = None if real else ("answer has only Gap/abstain lines" if claims else "no answer parsed (cut off or off-format)")
    rec = {"question": q, "mode": mode, "split": how, "entity_hits": hits,
           "groups": [{"label": g["label"], "drugs": [GENERIC_NAME[d] for d in g["drugs"]]} for g in groups],
           "drugs": [GENERIC_NAME[d] for g in groups_drugs for d in g], "sections_in_context": sorted({s["section"] for s in sources}),
           "sources": [{k2: v for k2, v in s.items() if k2 not in ("text", "drug_id")} for s in sources], "context_chars": len(context),
           "prompt_tokens": ptoks, "reasoning": reasoning, "retried_longer": retried, "truncated": truncated, "claims": claims,
           "unsupported_rate": rate, "raw_answer": raw, "final_answer": final, "abstained": not real, "abstain_reason": reason,
           "seconds": round(time.time() - t0, 1)}
    if verbose: print(f"\nQ: {q}\n mode={mode}/{how} drugs={rec['drugs']} prompt_tokens={ptoks} truncated={truncated}\n{final}\n ({rec['seconds']}s)")
    return rec
