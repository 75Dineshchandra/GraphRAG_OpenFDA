def parse_answer(raw):
    body = raw.split("ANSWER:")[-1] if "ANSWER:" in raw else raw           # scratchpad is stripped here
    claims = []
    for line in body.splitlines():
        line = line.strip()
        if not line.startswith(("-", "*", "\u2022")): continue
        text = line.lstrip("-*\u2022 ").strip()
        tags = []
        for a, b in re.findall(r"\[S(\d+)(?:\s*[-\u2013]\s*S?(\d+))?\]", text):
            tags += [f"S{n}" for n in range(int(a), int(b) + 1)] if b else [f"S{a}"]
        claims.append({"claim": re.sub(r"\[S[\d\s\-\u2013S]*\]", "", text).strip(), "tags": list(dict.fromkeys(tags)), "gap": text.lower().startswith("gap:")})
    return claims

CSTOP = STOP | {"this","that","from","have","with","text","label","retrieved","product","use","used"}
def overlap(claim, ev):
    cw = {w for w in re.findall(r"[a-z0-9]+", claim.lower()) if len(w) >= 4 and w not in CSTOP}
    ew = set(re.findall(r"[a-z0-9]+", ev.lower()))
    return (len(cw & ew) / len(cw)) if cw else 1.0

def verify(claims, sources):
    by = {s["tag"]: s for s in sources}
    for c in claims:
        if c["gap"]: c["status"] = "gap"; continue                        # gap lines are allowed, not checked
        if not c["tags"]: c["status"] = "no_citation"; continue
        if any(t not in by for t in c["tags"]): c["status"] = "invalid_citation"; continue
        ev = "\n".join(by[t]["text"] for t in c["tags"])
        if overlap(c["claim"], ev) >= 0.8: c["status"] = "supported"; continue     # code check first
        v = llm(f"Label text:\n{ev}\n\nClaim: {c['claim']}\n\nDoes the label text directly support the claim? Answer with one word: YES or NO.",
                temperature=0.0, num_predict=3)
        c["status"] = "supported" if v.upper().startswith("YES") else "unsupported"
    return claims

