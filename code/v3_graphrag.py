# ===== 7. candidate search, rerank, meaning split, cluster check =====
def search_query(q, extra=()):
    idxA = np.concatenate([IDX_BY_SECTION[s] for s in ("indications_and_usage", "purpose") if s in IDX_BY_SECTION])
    fused = defaultdict(float)
    for i, s in hybrid_rank([q], idxA, k=SEARCH_K): fused[i] += s
    for i, s in hybrid_rank([q], None, k=15): fused[i] += 0.5 * s           # all-section safety net
    cand = sorted(fused, key=lambda i: -fused[i])[:RERANK_N]
    cand += [i for i in extra if i not in cand]        # candidates from the original question join each phrase search
    if FLAGS["rerank"] and cand:
        sc = get_reranker().predict([(q, CHUNKS[i]["stamped"]) for i in cand], show_progress_bar=False)
        scores = {i: float(s) for i, s in zip(cand, sc)}
    else: scores = {i: fused.get(i, 0.0) for i in cand}
    return sorted(cand, key=lambda i: -scores[i]), scores

def drugs_from(cand, scores, n):
    best = {}
    for i in cand: best.setdefault(CHUNKS[i]["drug_id"], scores[i])
    out, seen = [], set()
    for d, s in sorted(best.items(), key=lambda x: -x[1]):
        h = label_hash(d)
        if h in seen: continue
        seen.add(h); out.append(d)
        if len(out) >= n: break
    return out

def llm_split(q):
    p = ("Return JSON only. If the question asks about two or three DIFFERENT things (two meanings of one word, or two conditions), "
         "give one short search phrase per thing. Each phrase must keep the main topic words of the question. "
         "If it asks about one thing, return an empty list.\nFormat: {\"phrases\": [\"...\"]}\nQuestion: " + q)
    r = llm_json(p)
    try: ph = [x.strip() for x in r["phrases"] if isinstance(x, str) and x.strip()]
    except Exception: return []
    return ph if 2 <= len(ph) <= 3 else []              # parse failure or more than 3 -> original query only

def cluster_groups(cand, scores):
    top = cand[:30]
    if len(top) < 8: return None
    from sklearn.cluster import KMeans
    lab = KMeans(2, n_init=5, random_state=0).fit(EMB[top]).labels_
    groups = [[i for i, l in zip(top, lab) if l == k] for k in (0, 1)]
    if min(len(g) for g in groups) < 3: return None
    if abs(max(scores[i] for i in groups[0]) - max(scores[i] for i in groups[1])) > CLUSTER_GAP: return None
    ds = [{CHUNKS[i]["drug_id"] for i in g} for g in groups]
    if len(ds[0] & ds[1]) / max(1, min(len(ds[0]), len(ds[1]))) > 0.5: return None
    return groups

def symptom_groups(q):
    phrases = llm_split(q) if FLAGS["split"] == "llm" else []
    cand0, sc0 = search_query(q)                           # the original question is always searched
    if phrases:
        gs = []
        for ph in phrases:                                 # each phrase search also sees the original question's top candidates
            cand, sc = search_query(ph, extra=cand0[:20]); gs.append({"label": ph, "drugs": drugs_from(cand, sc, POOL // len(phrases))})
        return gs, "llm-split"
    if FLAGS["split"] in ("llm", "cluster"):
        cl = cluster_groups(cand0, sc0)
