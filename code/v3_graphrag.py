def alias_hits(query):
    toks = [squash(t) for t in re.split(r"[\s/,?;:]+", query) if t]
    cand = {t for t in toks if len(t) >= 4} | {a + b for a, b in zip(toks, toks[1:]) if a and b}
    return [{"drug_id": g, "matched": f"alias:{a}", "n": 99} for a in cand if a not in BAD for g in ALIAS.get(a, ())]

def detect_entities(query):
    qn = " ".join(norm_tokens(query)); qt = set(qn.split()); hits = []
    exact, fuzzy = [], []
    for ts, nm, kind, eid in ENT:
        if ts <= qt: exact.append((ts, nm, kind, eid))
        elif len(ts) >= 5 and len(ts) - len(ts & qt) == 1: fuzzy.append((ts, nm, kind, eid))   # fallback only: long name, exactly 1 word missing
    hits = exact if exact else sorted(fuzzy, key=lambda h: -len(h[0]))[:1]
    qp = " " + qn + " "
    def spans(nm):
        ph, out, s = " " + " ".join(norm_tokens(nm)) + " ", [], 0
        while True:
            i = qp.find(ph, s)
            if i < 0: return out
            out.append((i, i + len(ph))); s = i + 1
    sp = {h[1]: spans(h[1]) for h in hits}
    keep = []
    for h in hits:                       # keep a shorter name only if it also appears outside the longer name's span
        longer = [o for o in hits if h[0] < o[0]]
        if not longer: keep.append(h); continue
        cover = [x for o in longer for x in sp[o[1]]]
        if [x for x in sp[h[1]] if not any(a <= x[0] and x[1] <= b for a, b in cover)]: keep.append(h)
    out = []
    for ts, nm, kind, eid in sorted(keep, key=lambda h: (-len(h[0]), len(h[1]))):
        for g in ([eid] if kind == "generic" else BRAND_TO_GENERIC.get(eid, [])): out.append({"drug_id": g, "matched": nm, "n": len(ts), "kind": "exact" if ts <= qt else "fuzzy"})
    if FLAGS["alias"]:
        skip = set().union(*[h[0] for h in keep]) if keep else set()
        al, seen_al = [], set()
        for h in alias_hits(query):
            if h["matched"][6:] in skip or h["drug_id"] in seen_al: continue    # skip aliases already inside a matched name
            seen_al.add(h["drug_id"]); al.append(dict(h, kind="alias"))
        out += al[:ALIAS_CAP]
    return out

