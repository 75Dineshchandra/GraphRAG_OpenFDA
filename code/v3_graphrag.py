SECTION_RANK = {s: i for i, s in enumerate(SECTION_ORDER)}
def build_block(d, wanted, missing_note, qvs, quota, tagc, sources):
    idxs = [i for i in IDX_BY_DRUG.get(d, []) if CHUNKS[i]["section"] in wanted]
    idxs = sorted(idxs, key=lambda i: -max(float(EMB[i] @ v) for v in qvs))
    chosen, used, seen = [], 0, set()
    for i in idxs:                                        # best chunk of every wanted section first
        s = CHUNKS[i]["section"]
        if s not in seen and used + len(CHUNKS[i]["text"]) <= quota: chosen.append(i); seen.add(s); used += len(CHUNKS[i]["text"])
    per_sec = Counter(CHUNKS[i]["section"] for i in chosen)
    for i in idxs:                                        # then fill the rest of the quota (max MAX_CHUNKS_PER_SECTION per section)
        sec = CHUNKS[i]["section"]
        if i not in chosen and per_sec[sec] < MAX_CHUNKS_PER_SECTION and used + len(CHUNKS[i]["text"]) <= quota:
            chosen.append(i); used += len(CHUNKS[i]["text"]); per_sec[sec] += 1
    chosen.sort(key=lambda i: (SECTION_RANK.get(CHUNKS[i]["section"], 99), i))
    have = {CHUNKS[i]["section"] for i in IDX_BY_DRUG.get(d, [])}
    lines = [f"### {GENERIC_NAME[d]}"]
    miss = [s for s in missing_note if s not in have]
    if miss: lines.append("NOTE: no text for " + ", ".join(miss) + ".")
    for i in chosen:
        tagc[0] += 1; tag = f"S{tagc[0]}"
        sources.append({"tag": tag, "drug_id": d, "drug": GENERIC_NAME[d], "section": CHUNKS[i]["section"], "node": CHUNKS[i]["cid"], "text": CHUNKS[i]["text"]})
        lines.append(f"[{tag}] ({CHUNKS[i]['section']}) {CHUNKS[i]['text']}")
    return "\n".join(lines)

def order_drugs(ds):
    if len(ds) >= 6: return [ds[0]] + ds[2:] + [ds[1]]     # best first, second-best last, never the best in the middle
    return ds

def build_context(q, groups_drugs, shrink=1.0, labels=None):
    wanted, top3 = choose_sections(q); qv = qvec(q)
    total = int(CONTEXT_TOKENS * CHARS_PER_TOKEN * shrink)
    live = [(g, lb) for g, lb in zip(groups_drugs, labels or [None] * len(groups_drugs)) if g]
    group_budget = total // max(1, len(live))              # budget per meaning group first
    tagc, sources, blocks = [0], [], []
    for g, lb in live:
        quota = min(group_budget // len(g), 9000)          # then per drug inside the group
        qvs = [qv] + ([qvec(lb)] if lb else [])            # chunks scored by the whole question AND the group's own phrase
        for d in order_drugs(g): blocks.append(build_block(d, wanted, top3, qvs, quota, tagc, sources))
    return "\n\n".join(blocks), sources

