"""## Step 4 - Reshape medical-o1 into the pipeline's grounded format (~3,000 examples)
Each medical-o1 answer passage becomes excerpt `[S1]`, and the target answer keeps the reasoning (shortened) plus a cited bullet in the exact answer contract of `build_prompt()`. This teaches grounded answering and citation habit (T1/T2 style) with the reasoning style you wanted, without any label text.
"""

def shorten(text, words):
    w = str(text).split()
    return " ".join(w[:words]) + (" ..." if len(w) > words else "")

rows = raw["train"].shuffle(seed=SEED)
part_a = []
