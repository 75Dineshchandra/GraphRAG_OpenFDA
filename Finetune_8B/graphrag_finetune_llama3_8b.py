MAX_LEN = 1024
def to_features(d):
    msgs = [{"role": "system", "content": d["system"]},
            {"role": "user", "content": d["user"]}]
    prompt_text = tokenizer.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
    full_text = prompt_text + d["assistant"] + tokenizer.eos_token
    prompt_ids = tokenizer(prompt_text, add_special_tokens=False)["input_ids"]
    full_ids = tokenizer(full_text, add_special_tokens=False)["input_ids"][:MAX_LEN]
    labels = ([-100] * len(prompt_ids) + full_ids[len(prompt_ids):])[:MAX_LEN]
    return {"input_ids": full_ids, "labels": labels, "attention_mask": [1] * len(full_ids)}

features = [to_features(d) for d in train_data]
print("tokenised:", len(features), "| example length:", len(features[0]["input_ids"]))

class ListDataset(Dataset):
    def __len__(self): return len(features)
    def __getitem__(self, i): return features[i]

def collate(batch):
    maxlen = max(len(b["input_ids"]) for b in batch)
    pad = tokenizer.pad_token_id
    input_ids, labels, attn = [], [], []
    for b in batch:
        n = maxlen - len(b["input_ids"])
        input_ids.append(b["input_ids"] + [pad] * n)
        labels.append(b["labels"] + [-100] * n)
        attn.append(b["attention_mask"] + [0] * n)
    return {"input_ids": torch.tensor(input_ids), "labels": torch.tensor(labels),
            "attention_mask": torch.tensor(attn)}

train_ds = ListDataset()

"""## Step 6 - QLoRA training on GPU
QLoRA exactly as scoped in the LabelTune plan: 4-bit base, LoRA adapters only, no full fine-tune. Batch 2 x grad-accum 8 = effective batch 16. Two epochs over ~3,000 examples is roughly 375 steps.
"""

